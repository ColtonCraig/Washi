'use strict';
/* Puts the extension toolbar code (electron-chrome-extensions/browser-action, MIT, Samuel Maddock) into preload.js.
   Washi's preload runs sandboxed and can't load packages, so the code is copied in between two markers.
   Run after updating electron-chrome-extensions:  node scripts/vendor-browser-action.js   (--check: fail if out of date) */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), pre = path.join(root, 'preload.js');
const pkg = require(path.join(root, 'node_modules/electron-chrome-extensions/package.json'));
const src = fs.readFileSync(path.join(root, 'node_modules/electron-chrome-extensions/dist/cjs/browser-action.js'), 'utf8');
const START = '/* ---- vendored: electron-chrome-extensions/browser-action', END = '/* ---- end vendored ---- */';
const block = `${START} ${pkg.version} (MIT, (c) Samuel Maddock) — generated by scripts/vendor-browser-action.js ---- */
const __browserActionModule = (() => { const module = { exports: {} }, exports = module.exports;
${src}
return module.exports; })();
${END}`;
let s = fs.readFileSync(pre, 'utf8');
const a = s.indexOf(START), b = s.indexOf(END);
const next = a > -1 && b > a ? s.slice(0, a) + block + s.slice(b + END.length) : s.trimEnd() + '\n\n' + block + '\n';
if (process.argv.includes('--check')) { if (next !== s) { console.error('preload.js is out of date: run node scripts/vendor-browser-action.js'); process.exit(1); } console.log('preload.js vendored code is current (' + pkg.version + ')'); process.exit(0); }
fs.writeFileSync(pre, next); console.log('vendored browser-action ' + pkg.version + ' into preload.js');
